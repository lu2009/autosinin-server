    fun pageHeadTemplate(): ByteArray = hexToBytes(PAGE_HEAD_HEX)
    fun feedsTemplate(): ByteArray = hexToBytes(FEEDS_HEX)

    fun buildPageHead(uin: String, tsMs: Long, seq: Int, trace: String): ByteArray =
        build(pageHeadTemplate(), OLD_TRACE_PAGE_HEAD, null, uin, tsMs, seq, trace)

    fun buildFeeds(uin: String, tsMs: Long, seq: Int, trace: String): ByteArray =
        build(feedsTemplate(), OLD_TRACE_FEEDS, OLD_FEEDS_SESSION, uin, tsMs, seq, trace)

    private fun build(
        template: ByteArray,
        oldTrace: String,
        oldSession: String?,
        uin: String,
        tsMs: Long,
        seq: Int,
        trace: String,
    ): ByteArray {
        require(seq in 1..127) { "seq 必须为 1..127" }
        // 模板是 10 位 uin；9 位账号补前导 0，保持 protobuf/JSON 长度不变。
        val templateUin = uin.padStart(10, '0')
        val safeTrace = if (trace.length == oldTrace.length) trace else {
            (templateUin + "_" + tsMs + "_" + (1000..9999).random())
                .take(oldTrace.length)
                .padEnd(oldTrace.length, '0')
        }
        val newJson = jsonFor(templateUin, tsMs)
        require(newJson.toByteArray().size == OLD_JSON.toByteArray().size) { "JSON 长度变化" }
        val b = template.copyOf()
        require(b.size > 1 && b[0] == 0x08.toByte()) { "模板 seq 位置不符" }
        b[1] = seq.toByte()
        replaceFirst(b, OLD_JSON.toByteArray(), newJson.toByteArray())
        if (oldSession != null) {
            val newSession = templateUin + "_" + tsMs
            require(newSession.length == oldSession.length)
            replaceAll(b, oldSession.toByteArray(), newSession.toByteArray())
        }
        replaceAll(b, oldTrace.toByteArray(), safeTrace.toByteArray())
        return b
    }

    /** JSON 只改 session/时间；所有替换必须等长。 */
    internal fun jsonFor(uin: String, tsMs: Long): String {
        val sec = tsMs / 1000
        var s = OLD_JSON
        s = s.replace(Regex("\"page_session_id\":\"[^\"]+\""), "\"page_session_id\":\"" + uin + "_" + tsMs + "\"")
        s = s.replace(Regex("\"base_timestamp\":\\d+"), "\"base_timestamp\":" + sec)
        s = s.replace(Regex("\"last_refresh_time\":\\d+"), "\"last_refresh_time\":" + sec)
        s = s.replace(Regex("basetime=\\d+"), "basetime=" + sec)
        s = s.replace(Regex("lastentertime=\\d+"), "lastentertime=" + sec)
        return s
    }

    private fun replaceFirst(buf: ByteArray, from: ByteArray, to: ByteArray) {
        val i = indexOf(buf, from, 0)
        require(i >= 0) { "找不到待替换片段" }
        System.arraycopy(to, 0, buf, i, to.size)
    }

    private fun replaceAll(buf: ByteArray, from: ByteArray, to: ByteArray) {
        require(from.size == to.size) { "替换必须等长" }
        var i = 0
        while (true) {
            val at = indexOf(buf, from, i)
            if (at < 0) return
            System.arraycopy(to, 0, buf, at, to.size)
            i = at + to.size
        }
    }

    private fun indexOf(buf: ByteArray, pat: ByteArray, start: Int): Int {
        outer@ for (i in start..buf.size - pat.size) {
            for (j in pat.indices) if (buf[i + j] != pat[j]) continue@outer
            return i
        }
        return -1
    }

    private fun hexToBytes(s: String): ByteArray {
        val clean = s.filter { it in '0'..'9' || it in 'a'..'f' }
        require(clean.length % 2 == 0)
        return ByteArray(clean.length / 2) { clean.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
    }
