    private fun buildFrom(template: ByteArray, p: Params): ByteArray {
        require(p.seq in 1..127) { "seq 必须为 1..127" }
        val b = PbEdit.replace(
            template,
            listOf(
                CAP_TS to varint(p.ts),
                CAP_TRACE.toByteArray() to p.trace.toByteArray(),
                CAP_UUID.toByteArray() to p.uuid.toByteArray(),
                CAP_UIN.toByteArray() to p.uin.toByteArray(),
            ),
        )
        require(b.size > 1 && b[0] == 0x08.toByte() && (b[1].toInt() and 0x7f) == 0x05) { "模板 seq 位置不符" }
        b[1] = p.seq.toByte()
        return b
    }

    private fun varint(v: Long): ByteArray {
        var x = v
        val out = ArrayList<Byte>()
        while (true) {
            val b = (x and 0x7f).toInt()
            x = x ushr 7
            if (x == 0L) { out.add(b.toByte()); break }
            out.add((b or 0x80).toByte())
        }
        return out.toByteArray()
    }

    private fun replaceFirst(buf: ByteArray, from: ByteArray, to: ByteArray) {
        val i = indexOf(buf, from, 0)
        require(i >= 0) { "找不到待替换片段" }
        System.arraycopy(to, 0, buf, i, to.size)
    }

    private fun replaceAll(buf: ByteArray, from: ByteArray, to: ByteArray) {
        require(from.size == to.size) { "替换必须等长" }
        var i = 0
        while (true) {
            val at = indexOf(buf, from, i)
            if (at < 0) return
            System.arraycopy(to, 0, buf, at, to.size)
            i = at + to.size
        }
    }

    private fun indexOf(buf: ByteArray, pat: ByteArray, start: Int): Int {
        outer@ for (i in start..buf.size - pat.size) {
            for (j in pat.indices) if (buf[i + j] != pat[j]) continue@outer
            return i
        }
        return -1
    }

    private fun hexToBytes(s: String): ByteArray {
        val clean = s.filter { it in '0'..'9' || it in 'a'..'f' }
        require(clean.length % 2 == 0)
        return ByteArray(clean.length / 2) { clean.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
    }
