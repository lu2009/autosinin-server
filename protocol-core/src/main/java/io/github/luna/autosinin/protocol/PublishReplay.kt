    data class Params(
        val uin: String,
        val trace: String,
        val uuid: String,
        val ts: Long = System.currentTimeMillis() / 1000,
        val seq: Int = 5,
    )

    fun build(p: Params): ByteArray = buildFrom(template(), p)

