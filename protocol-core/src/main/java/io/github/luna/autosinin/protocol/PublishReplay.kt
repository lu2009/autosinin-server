    /** 成功回包：envelope.field4 -> payload.field2 -> feed.field1 存在。错误短回包不满足。 */
    fun isSuccessResponse(b: ByteArray?): Boolean {
        if (b == null || b.isEmpty()) return false
        val env = FarmProto.decode(b)
        val payload = env.bytes(4) ?: return false
        val p = FarmProto.decode(payload)
        val feed = p.bytes(2) ?: return false
        val f = FarmProto.decode(feed)
        return (f.bytes(1)?.size ?: 0) > 0
    }

